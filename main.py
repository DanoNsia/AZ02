#
# Самостоятельно создайте DataFrame с данными
#
# Выведите первые несколько строк DataFrame, чтобы убедиться, что данные загружены правильно
#
# Вычислите среднюю оценку по каждому предмету
#
# Вычислите медианную оценку по каждому предмету
#
# Вычислите Q1 и Q3 для оценок по математике:
#
# Q1_math = df['Математика'].quantile(0.25)
#
# Q3_math = df['Математика'].quantile(0.75)
#
# можно также попробовать рассчитать IQR
# Вычислите стандартное отклонение

import pandas as pd
import numpy as np

# Шаг 1: Создание DataFrame с данными
data = {
    'Ученик': [f'Ученик {i}' for i in range(1, 11)],
    'Математика': [85, 78, 92, 88, 76, 95, 89, 73, 84, 91],
    'Физика': [82, 79, 85, 90, 86, 88, 91, 75, 80, 87],
    'Химия': [78, 82, 88, 85, 80, 90, 86, 77, 84, 83],
    'Литература': [92, 85, 88, 91, 79, 87, 84, 83, 86, 90],
    'История': [89, 84, 91, 87, 80, 86, 90, 81, 85, 88]
}

df = pd.DataFrame(data)

# Шаг 2: Вывод первых нескольких строк DataFrame
print("Первые несколько строк DataFrame:")
print(df.head())

# Шаг 3: Вычисление средней оценки по каждому предмету
mean_scores = df.mean(numeric_only=True)
print("\nСредняя оценка по каждому предмету:")
print(mean_scores)

# Шаг 4: Вычисление медианной оценки по каждому предмету
median_scores = df.median(numeric_only=True)
print("\nМедианная оценка по каждому предмету:")
print(median_scores)

# Шаг 5: Вычисление Q1 и Q3 для оценок по математике
Q1_math = df['Математика'].quantile(0.25)
Q3_math = df['Математика'].quantile(0.75)
IQR_math = Q3_math - Q1_math

print(f"\nQ1 для Математики: {Q1_math}")
print(f"Q3 для Математики: {Q3_math}")
print(f"IQR для Математики: {IQR_math}")

# Шаг 6: Вычисление стандартного отклонения
std_deviation = df.std(numeric_only=True)
print("\nСтандартное отклонение по каждому предмету:")
print(std_deviation)